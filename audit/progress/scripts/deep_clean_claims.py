import re
from pathlib import Path

html_files = [p for p in Path('.').rglob('*.html') if not str(p).startswith('audit') and '.gemini' not in str(p) and 'node_modules' not in p.as_posix() and 'components/' not in p.as_posix()]

replacements = [
    # Guarantee / Warranty
    (r'ضمان شامل بأعلى معايير الجودة', 'عناية فائقة وتعهد بالسلامة'),
    (r'وضماناً شاملاً بأعلى معايير الجودة', 'وعناية فائقة تتعهد'),
    (r'ضماناً كتابياً شاملاً بنسبة بأعلى معايير الجودة', 'عناية فائقة وتعهداً كتابياً'),
    (r'وضمان شامل', 'وعناية فائقة بالمنقولات'),
    (r'مع الضمان', 'مع الحرص التام على السلامة'),
    (r'بضمان', 'بعناية فائقة وحرص على'),
    (r'لضمان الإنجاز بمع الحرص على الالتزام بالموعد المحدد', 'لتحقيق الإنجاز مع الالتزام بالموعد المحدد'),
    (r'لضمان سرعة', 'لتسهيل سرعة'),
    (r'لضمان سلامة', 'للحفاظ على سلامة'),
    (r'لضمان ثبات', 'للحفاظ على ثبات'),
    (r'لضمان حماية', 'لحماية'),
    (r'لضمان جودة', 'لتحقيق أعلى جودة في'),
    (r'لضمان النقل', 'لتنفيذ النقل'),
    (r'لضمان وصول', 'لتأمين وصول'),
    (r'لضمان عدم', 'لتفادي'),
    (r'لضمان', 'لتأمين'),
    
    # Superlatives
    (r'أفضل شركة ونش رفع عفش بجدة', 'شركة ونش رفع عفش متخصصة بجدة'),
    (r'أفضل شركة تخزين عفش بجدة', 'شركة تخزين عفش متخصصة بجدة'),
    (r'أفضل شركة هي شركات نقل العفش بجدة؟', 'الشركات الأنسب لنقل العفش بجدة؟'),
    (r'هل أرخص شركة هي', 'هل الأقل سعراً هي'),
    (r'أرخص عرض ليس دائمًا الأوفر', 'العرض الأقل سعراً ليس دائماً الأوفر'),
    (r'أرخص الأسعار', 'أسعار مناسبة ومنافسة'),
    (r'الأرخص', 'المناسبة اقتصادياً'),
    (r'أرخص', 'أقل تكلفة'),
    
    # Specific broken remnants
    (r'بمع الحرص على الالتزام بالموعد المحدد', 'مع الحرص على الالتزام بالموعد المحدد'),
    (r'شركة موثوقة ومتميزة للتخلص من الأثاث القديم والرجيع بجدة، شركة معتمدة', 'شركة موثوقة ومتميزة للتخلص من الأثاث القديم والرجيع بجدة'),
    (r'شركة موثوقة ومتميزة نقل عفش عمالة فلبينية بجدة مع عناية فائقة وتعهد بالسلامة', 'شركة موثوقة ومتميزة نقل عفش عمالة فلبينية بجدة مع فك وتركيب متقن'),
    (r'بخبرة أكثر من 15 عاماً من شركة نجوم العرب مع عناية فائقة وتعهد بالسلامة', 'بخبرة واحترافية عالية من شركة نجوم العرب مع فك وتركيب متقن')
]

modified_count = 0
for p in sorted(html_files):
    c = p.read_text(encoding='utf-8')
    orig = c
    for pat, repl in replacements:
        c = re.sub(pat, repl, c)
    if c != orig:
        p.write_text(c, encoding='utf-8')
        modified_count += 1

print(f"Deep cleaned claims in {modified_count} HTML files.")
