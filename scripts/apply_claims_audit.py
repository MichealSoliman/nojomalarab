components_files = ['components/footer.html']

all_targets = files + components_files

for f in all_targets:
    with open(f, 'r', encoding='utf-8', errors='ignore') as fp:
        content = fp.read()
    
    modified = False
    for old_t, new_t, reason in replacements:
        if old_t in content:
            # find line number
            lines = content.splitlines()
            for line_no, l in enumerate(lines, 1):
                if old_t in l:
                    records.append({
                        'file': f,
                        'line': line_no,
                        'old_text': old_t,
                        'new_text': new_t,
                        'reason': reason
                    })
            content = content.replace(old_t, new_t)
            modified = True
            
    # Also handle carpenter table market comparison removal specifically
